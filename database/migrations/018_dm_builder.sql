DECLARE
  r record;
BEGIN
  FOR r IN
    WITH t AS (SELECT unnest(ARRAY['meta.dm_entity', 'meta.dm_entity_key', 'meta.dm_mart', 'meta.dm_mart_version',
                 'meta.dm_mart_source', 'meta.dm_mart_field', 'meta.dm_mart_field_source', 'meta.dm_mart_filter',
