-- Type family of a column type: keys of one entity must share it (D2).
CREATE FUNCTION meta.dm_type_family(p_type regtype) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS $fn$
  SELECT CASE WHEN p_type IN ('smallint'::regtype, 'integer'::regtype, 'bigint'::regtype, 'numeric'::regtype) THEN 'NUMBER'
              WHEN p_type IN ('text'::regtype, 'character varying'::regtype, 'character'::regtype) THEN 'TEXT'
              ELSE format_type(p_type, NULL) END
$fn$;

-- format_type() spelling of a whitelisted field type, to compare with the catalog.
CREATE FUNCTION meta.dm_type_canonical(p_type text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS $fn$
  SELECT CASE p_type WHEN 'timestamp' THEN 'timestamp without time zone'
                     WHEN 'timestamptz' THEN 'timestamp with time zone'
                     ELSE regexp_replace(p_type, '^varchar', 'character varying') END
$fn$;

-- Type of a column of an ODS table, or NULL when the table or the column does not exist.
CREATE FUNCTION meta.dm_ods_column_type(p_table text, p_column text) RETURNS regtype
LANGUAGE sql STABLE SET search_path = pg_catalog AS $fn$
  SELECT a.atttypid::regtype FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'ods' AND c.relname = p_table AND c.relkind IN ('r', 'p', 'v', 'm')
     AND a.attname = p_column AND a.attnum > 0 AND NOT a.attisdropped
$fn$;

CREATE FUNCTION meta.dm_actor_username(p_actor bigint) RETURNS text
LANGUAGE sql STABLE SET search_path = pg_catalog AS $fn$
  SELECT left(coalesce(nullif(current_setting('dwh.actor_username', true), ''), 'user ' || p_actor), 255)
$fn$;

-- Whether dm.<code> has exactly the columns of the fields of the version (+ dm_loaded_at) with their types.
CREATE FUNCTION meta.dm_mart_table_matches(p_version_id bigint) RETURNS boolean
LANGUAGE sql STABLE SET search_path = pg_catalog, meta AS $fn$
  WITH v AS (SELECT m.mart_code FROM meta.dm_mart_version x JOIN meta.dm_mart m ON m.mart_id = x.mart_id
              WHERE x.version_id = p_version_id),
  want AS (SELECT f.field_name AS name, meta.dm_type_canonical(f.data_type) AS typ FROM meta.dm_mart_field f
            WHERE f.version_id = p_version_id
           UNION ALL SELECT 'dm_loaded_at', 'timestamp with time zone'),
  have AS (SELECT a.attname::text AS name, format_type(a.atttypid, a.atttypmod) AS typ
             FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'dm' AND c.relname = (SELECT mart_code FROM v) AND c.relkind = 'r'
              AND a.attnum > 0 AND NOT a.attisdropped)
  SELECT EXISTS (SELECT 1 FROM have) AND NOT EXISTS ((SELECT * FROM want EXCEPT SELECT * FROM have)
                                                    UNION ALL (SELECT * FROM have EXCEPT SELECT * FROM want))
$fn$;

-- The AI whitelist row of a mart follows the mart (D10): active only when the mart is active, ai_enabled
-- and has a published version. Rows are never deleted (016: only deactivated).
CREATE FUNCTION meta.dm_mart_sync_ai(p_mart_id bigint, p_actor bigint) RETURNS void
LANGUAGE plpgsql SET search_path = pg_catalog, meta AS $fn$
DECLARE
  m meta.dm_mart;
  v_on boolean;
BEGIN
  SELECT * INTO m FROM meta.dm_mart x WHERE x.mart_id = p_mart_id;
  v_on := m.is_active AND m.ai_enabled
          AND EXISTS (SELECT 1 FROM meta.dm_mart_version v WHERE v.mart_id = m.mart_id AND v.status = 'PUBLISHED');
  IF v_on THEN
    INSERT INTO meta.ai_report_object AS o (schema_name, object_name, title, description, required_permission_code,
                                            is_active, updated_at, updated_by_user_id)
    VALUES ('dm', m.mart_code, m.title, m.description, m.required_permission_code, true, clock_timestamp(), p_actor)
    ON CONFLICT (schema_name, object_name) DO UPDATE
      SET title = EXCLUDED.title, description = EXCLUDED.description,
          required_permission_code = EXCLUDED.required_permission_code, is_active = true,
          updated_at = EXCLUDED.updated_at, updated_by_user_id = EXCLUDED.updated_by_user_id;
  ELSE
    UPDATE meta.ai_report_object o SET is_active = false, updated_at = clock_timestamp(), updated_by_user_id = p_actor
     WHERE o.schema_name = 'dm' AND o.object_name = m.mart_code AND o.is_active;
  END IF;
END;
$fn$;

-- Checks a saved version against the catalog; returns the list of problems (empty = valid).
CREATE FUNCTION meta.dm_mart_version_problems(p_version_id bigint) RETURNS text[]
LANGUAGE plpgsql STABLE SET search_path = pg_catalog, meta AS $fn$
DECLARE
  v meta.dm_mart_version;
  p text[] := ARRAY[]::text[];
  src record;
  f record;
  k record;
  v_kinds text[];
  v_keys integer;
BEGIN
  SELECT * INTO v FROM meta.dm_mart_version x WHERE x.version_id = p_version_id;
  IF v.grain_entity_id IS NULL THEN p := p || 'grain entity is not set'::text; END IF;
  IF NOT EXISTS (SELECT 1 FROM meta.dm_mart_source x WHERE x.version_id = p_version_id AND x.source_kind = 'GRAIN') THEN
    p := p || 'GRAIN source is missing'::text;
  END IF;
  FOR src IN SELECT * FROM meta.dm_mart_source x WHERE x.version_id = p_version_id ORDER BY x.position LOOP
    IF to_regclass(format('ods.%I', src.table_name)) IS NULL THEN
      p := p || format('source %s: table ods.%s not found', src.alias, src.table_name);
      CONTINUE;
    END IF;
    IF meta.dm_ods_column_type(src.table_name, src.key_column) IS NULL THEN
      p := p || format('source %s: column %s not found', src.alias, src.key_column);
    END IF;
    IF src.source_kind <> 'LOOKUP' AND NOT EXISTS (SELECT 1 FROM meta.dm_entity_key ek
         WHERE ek.entity_id = v.grain_entity_id AND ek.table_name = src.table_name AND ek.column_name = src.key_column
           AND ek.is_active) THEN
      p := p || format('source %s: %s.%s is not an active key of the grain entity', src.alias, src.table_name, src.key_column);
    END IF;
    IF src.source_kind = 'LOOKUP' THEN
      SELECT x.* INTO k FROM meta.dm_mart_source x WHERE x.version_id = p_version_id AND x.alias = src.ref_alias;
      IF k.source_id IS NULL OR k.position >= src.position THEN
        p := p || format('source %s: reference %s must be an earlier source', src.alias, src.ref_alias);
      ELSIF k.source_kind = 'CHILD' THEN
        p := p || format('source %s: a lookup cannot refer to the CHILD source %s', src.alias, src.ref_alias);
      ELSIF meta.dm_ods_column_type(k.table_name, src.ref_column) IS NULL THEN
        p := p || format('source %s: column %s.%s not found', src.alias, src.ref_alias, src.ref_column);
      ELSIF meta.dm_ods_column_type(src.table_name, src.key_column) IS NOT NULL
            AND meta.dm_type_family(meta.dm_ods_column_type(k.table_name, src.ref_column))
                <> meta.dm_type_family(meta.dm_ods_column_type(src.table_name, src.key_column)) THEN
        p := p || format('source %s: types of %s.%s and %s differ', src.alias, src.ref_alias, src.ref_column, src.key_column);
      END IF;
      k := NULL;
    END IF;
  END LOOP;
  SELECT count(*) INTO v_keys FROM meta.dm_mart_field x WHERE x.version_id = p_version_id AND x.is_key;
  IF v_keys <> 1 THEN p := p || 'exactly one key field is required'::text; END IF;
  IF NOT EXISTS (SELECT 1 FROM meta.dm_mart_field x WHERE x.version_id = p_version_id AND NOT x.is_key) THEN
    p := p || 'at least one field besides the key is required'::text;
  END IF;
  FOR f IN SELECT x.*, s.source_kind, s.table_name, s.key_column
             FROM meta.dm_mart_field d JOIN meta.dm_mart_field_source x ON x.field_id = d.field_id
             LEFT JOIN meta.dm_mart_source s ON s.version_id = d.version_id AND s.alias = x.source_alias
            WHERE d.version_id = p_version_id ORDER BY d.position, x.priority_no LOOP
    IF f.source_kind IS NULL THEN
      p := p || format('field source %s: unknown source %s', f.field_source_id, f.source_alias);
    ELSIF to_regclass(format('ods.%I', f.table_name)) IS NOT NULL
          AND meta.dm_ods_column_type(f.table_name, f.source_column) IS NULL THEN
      p := p || format('column %s.%s not found', f.source_alias, f.source_column);
    ELSIF f.source_kind = 'CHILD' AND f.aggregate_fn = 'NONE' THEN
      p := p || format('column %s.%s of a CHILD source needs an aggregate', f.source_alias, f.source_column);
    ELSIF f.source_kind <> 'CHILD' AND f.aggregate_fn <> 'NONE' THEN
      p := p || format('aggregate is allowed only for CHILD sources (%s.%s)', f.source_alias, f.source_column);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM meta.dm_mart_field d WHERE d.version_id = p_version_id
              AND NOT EXISTS (SELECT 1 FROM meta.dm_mart_field_source x WHERE x.field_id = d.field_id)) THEN
    p := p || 'every field needs at least one source column'::text;
  END IF;
  IF EXISTS (SELECT 1 FROM meta.dm_mart_field d WHERE d.version_id = p_version_id AND d.is_key
              AND NOT (1 = (SELECT count(*) FROM meta.dm_mart_field_source x WHERE x.field_id = d.field_id)
                       AND EXISTS (SELECT 1 FROM meta.dm_mart_field_source x JOIN meta.dm_mart_source s
                                     ON s.version_id = d.version_id AND s.alias = x.source_alias
                                    WHERE x.field_id = d.field_id AND s.source_kind = 'GRAIN'
                                      AND x.source_column = s.key_column AND x.aggregate_fn = 'NONE'))) THEN
    p := p || 'the key field must be the key column of the GRAIN source'::text;
  END IF;
  FOR f IN SELECT x.*, s.table_name FROM meta.dm_mart_filter x
             LEFT JOIN meta.dm_mart_source s ON s.version_id = x.version_id AND s.alias = x.source_alias
            WHERE x.version_id = p_version_id ORDER BY x.position LOOP
    IF f.table_name IS NULL THEN
      p := p || format('filter %s: unknown source %s', f.position, f.source_alias);
    ELSIF to_regclass(format('ods.%I', f.table_name)) IS NOT NULL
          AND meta.dm_ods_column_type(f.table_name, f.column_name) IS NULL THEN
