-- A new DRAFT version: a copy of the published one (or empty). One draft per mart.
CREATE FUNCTION app.dm_mart_version_create(p_token_hash text, p_mart_id bigint)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app, meta, audit AS $fn$
DECLARE
  v_actor bigint := app.integration_admin_session_user(p_token_hash);
  pub meta.dm_mart_version;
  v_id bigint;
  f record;
  v_field bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM meta.dm_mart m WHERE m.mart_id = p_mart_id) THEN RAISE EXCEPTION 'Mart not found'; END IF;
  IF EXISTS (SELECT 1 FROM meta.dm_mart_version v WHERE v.mart_id = p_mart_id AND v.status = 'DRAFT') THEN
    RAISE EXCEPTION 'Mart already has a draft version';
  END IF;
  SELECT * INTO pub FROM meta.dm_mart_version v WHERE v.mart_id = p_mart_id AND v.status = 'PUBLISHED';
  INSERT INTO meta.dm_mart_version (mart_id, version_no, grain_entity_id, created_by_user_id)
  VALUES (p_mart_id, coalesce((SELECT max(v.version_no) FROM meta.dm_mart_version v WHERE v.mart_id = p_mart_id), 0) + 1,
          pub.grain_entity_id, v_actor)
  RETURNING version_id INTO v_id;
  IF pub.version_id IS NOT NULL THEN
    INSERT INTO meta.dm_mart_source (version_id, position, alias, table_name, source_kind, key_column, ref_alias, ref_column)
    SELECT v_id, s.position, s.alias, s.table_name, s.source_kind, s.key_column, s.ref_alias, s.ref_column
      FROM meta.dm_mart_source s WHERE s.version_id = pub.version_id;
    FOR f IN SELECT * FROM meta.dm_mart_field d WHERE d.version_id = pub.version_id LOOP
      INSERT INTO meta.dm_mart_field (version_id, position, field_name, title, data_type, is_key)
      VALUES (v_id, f.position, f.field_name, f.title, f.data_type, f.is_key) RETURNING field_id INTO v_field;
      INSERT INTO meta.dm_mart_field_source (field_id, priority_no, source_alias, source_column, aggregate_fn)
      SELECT v_field, x.priority_no, x.source_alias, x.source_column, x.aggregate_fn
        FROM meta.dm_mart_field_source x WHERE x.field_id = f.field_id;
    END LOOP;
    INSERT INTO meta.dm_mart_filter (version_id, position, source_alias, column_name, operator, value)
    SELECT v_id, x.position, x.source_alias, x.column_name, x.operator, x.value
      FROM meta.dm_mart_filter x WHERE x.version_id = pub.version_id;
  END IF;
  PERFORM audit.log_security_event('DM_MART_VERSION_CREATED', 'DM_MART', p_mart_id::text, 'CREATE', 'SUCCESS',
    jsonb_build_object('actor_user_id', v_actor, 'version_id', v_id));
  RETURN v_id;
END;
