CREATE FUNCTION app.dm_mart_run_request_cancel(p_token_hash text, p_request_id bigint)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app, etl, audit AS $fn$
DECLARE
  v_actor bigint := app.integration_run_admin_session_user(p_token_hash);
  v_mart bigint;
BEGIN
  UPDATE etl.dm_mart_run_request x SET status = 'CANCELLED', finished_at = clock_timestamp(), result_code = 'CANCELLED',
         message = 'Cancelled before execution'
   WHERE x.request_id = p_request_id AND x.status = 'QUEUED'
  RETURNING x.mart_id INTO v_mart;
  IF v_mart IS NULL THEN
    IF NOT EXISTS (SELECT 1 FROM etl.dm_mart_run_request x WHERE x.request_id = p_request_id) THEN
      RAISE EXCEPTION 'Run request does not exist';
    END IF;
    RAISE EXCEPTION 'Only QUEUED run requests can be cancelled';
  END IF;
  PERFORM audit.log_security_event('DM_MART_RUN_REQUEST_CANCELLED', 'DM_MART', v_mart::text, 'CANCEL', 'SUCCESS',
    jsonb_build_object('request_id', p_request_id, 'actor_user_id', v_actor));
  RETURN true;
END;
$fn$;

