  UPDATE meta.dm_mart_version y SET status = 'PUBLISHED', published_at = clock_timestamp(), published_by_user_id = v_actor,
         ddl_status = CASE WHEN y.ddl_status = 'PROPOSED' THEN 'REJECTED' ELSE y.ddl_status END
   WHERE y.version_id = p_version_id;
  PERFORM meta.dm_mart_sync_ai(v.mart_id, v_actor);
  PERFORM audit.log_security_event('DM_MART_VERSION_PUBLISHED', 'DM_MART', v.mart_id::text, 'PUBLISH', 'SUCCESS',
    jsonb_build_object('actor_user_id', v_actor, 'version_id', p_version_id, 'version_no', v.version_no));
  RETURN true;
END;
