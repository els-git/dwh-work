-- D9: the DDL is generated by the database; a later package applies it after the SHA-256 check.
CREATE FUNCTION app.dm_mart_ddl_propose(p_token_hash text, p_version_id bigint)
RETURNS TABLE(ddl_text text, ddl_sha256 text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app, meta, audit AS $fn$
DECLARE
  v_actor bigint := app.integration_admin_session_user(p_token_hash);
  v meta.dm_mart_version;
  v_problems text[];
  v_text text;
BEGIN
  SELECT * INTO v FROM meta.dm_mart_version y WHERE y.version_id = p_version_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Mart version not found'; END IF;
  IF v.status <> 'DRAFT' THEN RAISE EXCEPTION 'DDL can be proposed only for a DRAFT version'; END IF;
  v_problems := meta.dm_mart_version_problems(p_version_id);
  IF cardinality(v_problems) > 0 THEN RAISE EXCEPTION 'Version is not valid: %', array_to_string(v_problems, '; '); END IF;
  IF meta.dm_mart_table_matches(p_version_id) THEN RAISE EXCEPTION 'The mart table already has this structure'; END IF;
  v_text := meta.dm_mart_ddl_text(p_version_id);
  UPDATE meta.dm_mart_version y SET ddl_status = 'PROPOSED', ddl_text = v_text,
         ddl_sha256 = encode(sha256(convert_to(v_text, 'UTF8')), 'hex'), updated_at = clock_timestamp()
   WHERE y.version_id = p_version_id;
  PERFORM audit.log_security_event('DM_MART_DDL_PROPOSED', 'DM_MART', v.mart_id::text, 'CREATE', 'SUCCESS',
    jsonb_build_object('actor_user_id', v_actor, 'version_id', p_version_id));
  RETURN QUERY SELECT v_text, encode(sha256(convert_to(v_text, 'UTF8')), 'hex');
END;
$fn$;

