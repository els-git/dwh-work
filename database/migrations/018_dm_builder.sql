-- Replaces the whole content of a DRAFT version. Definition (jsonb):
--   {"grain_entity_id": 1,
--    "sources": [{"alias": "c", "table": "clients", "kind": "GRAIN"},
--                {"alias": "st", "table": "status_ref", "kind": "LOOKUP", "ref_alias": "c", "ref_column": "status_code",
--                 "lookup_column": "code"}, ...],
--    "fields":  [{"name": "client_id", "title": "...", "type": "bigint", "is_key": true,
--                 "sources": [{"alias": "c", "column": "client_id"}]},
--                {"name": "balance", "type": "numeric", "sources": [{"alias": "a", "column": "amount", "aggregate": "SUM"}]}],
--    "filters": [{"alias": "a", "column": "state", "operator": "=", "value": "OPEN"}]}
-- Positions follow the order of the arrays, priorities the order of "sources" of a field. Returns the
-- problems found against the catalog (empty array = the version can be published once its table matches).
CREATE FUNCTION app.dm_mart_version_save(p_token_hash text, p_version_id bigint, p_definition jsonb)
RETURNS text[]
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app, meta, audit AS $fn$
DECLARE
  v_actor bigint := app.integration_admin_session_user(p_token_hash);
  v meta.dm_mart_version;
  d jsonb := coalesce(p_definition, '{}'::jsonb);
  e record;
  x record;
  v_kind text;
  v_key text;
  v_field bigint;
BEGIN
  SELECT * INTO v FROM meta.dm_mart_version y WHERE y.version_id = p_version_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Mart version not found'; END IF;
  IF v.status <> 'DRAFT' THEN RAISE EXCEPTION 'Only a DRAFT version can be changed'; END IF;
  IF jsonb_typeof(d) <> 'object' OR jsonb_typeof(coalesce(d->'sources', '[]')) <> 'array'
     OR jsonb_typeof(coalesce(d->'fields', '[]')) <> 'array' OR jsonb_typeof(coalesce(d->'filters', '[]')) <> 'array' THEN
    RAISE EXCEPTION 'Invalid mart definition';
  END IF;
  IF jsonb_array_length(coalesce(d->'sources', '[]')) > 30 OR jsonb_array_length(coalesce(d->'fields', '[]')) > 300
     OR jsonb_array_length(coalesce(d->'filters', '[]')) > 50 THEN
    RAISE EXCEPTION 'Mart definition is too large';
  END IF;
  IF d->>'grain_entity_id' IS NOT NULL AND NOT EXISTS (SELECT 1 FROM meta.dm_entity en
       WHERE en.entity_id = (d->>'grain_entity_id')::bigint AND en.is_active) THEN
    RAISE EXCEPTION 'Grain entity not found or inactive';
  END IF;
  DELETE FROM meta.dm_mart_filter y WHERE y.version_id = p_version_id;
  DELETE FROM meta.dm_mart_field y WHERE y.version_id = p_version_id;
  DELETE FROM meta.dm_mart_source y WHERE y.version_id = p_version_id;
  UPDATE meta.dm_mart_version y SET grain_entity_id = (d->>'grain_entity_id')::bigint, updated_at = clock_timestamp(),
         ddl_status = CASE WHEN y.ddl_status = 'PROPOSED' THEN 'NONE' ELSE y.ddl_status END,
         ddl_text = CASE WHEN y.ddl_status = 'PROPOSED' THEN NULL ELSE y.ddl_text END,
         ddl_sha256 = CASE WHEN y.ddl_status = 'PROPOSED' THEN NULL ELSE y.ddl_sha256 END
   WHERE y.version_id = p_version_id;
  FOR e IN SELECT value AS j, ordinality AS n FROM jsonb_array_elements(coalesce(d->'sources', '[]')) WITH ORDINALITY LOOP
    v_kind := upper(coalesce(e.j->>'kind', ''));
    IF v_kind = 'LOOKUP' THEN
      v_key := e.j->>'lookup_column';
    ELSE
      SELECT k.column_name INTO v_key FROM meta.dm_entity_key k
       WHERE k.entity_id = (d->>'grain_entity_id')::bigint AND k.table_name = e.j->>'table' AND k.is_active;
      IF v_key IS NULL THEN
        RAISE EXCEPTION 'Source %: table % has no active key of the grain entity', e.j->>'alias', e.j->>'table';
      END IF;
    END IF;
    INSERT INTO meta.dm_mart_source (version_id, position, alias, table_name, source_kind, key_column, ref_alias, ref_column)
    VALUES (p_version_id, e.n, e.j->>'alias', e.j->>'table', v_kind, v_key,
            CASE WHEN v_kind = 'LOOKUP' THEN e.j->>'ref_alias' END, CASE WHEN v_kind = 'LOOKUP' THEN e.j->>'ref_column' END);
    v_key := NULL;
  END LOOP;
  FOR e IN SELECT value AS j, ordinality AS n FROM jsonb_array_elements(coalesce(d->'fields', '[]')) WITH ORDINALITY LOOP
    IF jsonb_typeof(coalesce(e.j->'sources', '[]')) <> 'array' THEN RAISE EXCEPTION 'Invalid field %', e.j->>'name'; END IF;
    INSERT INTO meta.dm_mart_field (version_id, position, field_name, title, data_type, is_key)
    VALUES (p_version_id, e.n, e.j->>'name', nullif(btrim(coalesce(e.j->>'title', '')), ''), lower(e.j->>'type'),
            coalesce((e.j->>'is_key')::boolean, false))
    RETURNING field_id INTO v_field;
    FOR x IN SELECT value AS j, ordinality AS n FROM jsonb_array_elements(coalesce(e.j->'sources', '[]')) WITH ORDINALITY LOOP
      INSERT INTO meta.dm_mart_field_source (field_id, priority_no, source_alias, source_column, aggregate_fn)
      VALUES (v_field, x.n, x.j->>'alias', x.j->>'column', upper(coalesce(x.j->>'aggregate', 'NONE')));
    END LOOP;
  END LOOP;
  FOR e IN SELECT value AS j, ordinality AS n FROM jsonb_array_elements(coalesce(d->'filters', '[]')) WITH ORDINALITY LOOP
    INSERT INTO meta.dm_mart_filter (version_id, position, source_alias, column_name, operator, value)
    VALUES (p_version_id, e.n, e.j->>'alias', e.j->>'column', upper(e.j->>'operator'),
            CASE WHEN e.j->'value' = 'null'::jsonb THEN NULL ELSE e.j->'value' END);
  END LOOP;
  PERFORM audit.log_security_event('DM_MART_VERSION_SAVED', 'DM_MART', v.mart_id::text, 'SAVE', 'SUCCESS',
    jsonb_build_object('actor_user_id', v_actor, 'version_id', p_version_id));
  RETURN meta.dm_mart_version_problems(p_version_id);
END;
$fn$;

